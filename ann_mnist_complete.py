# ----------------------------- Reproducibility -----------------------------

def set_seed(seed=42):
    random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


# ----------------------------- MNIST loading -------------------------------

def load_mnist(data_dir="./data", quick=False):
    transform = transforms.ToTensor()  # converts uint8 pixels to float in [0, 1]
    train_ds = datasets.MNIST(data_dir, train=True, download=True, transform=transform)
    test_ds = datasets.MNIST(data_dir, train=False, download=True, transform=transform)

    x_train = train_ds.data.float().view(-1, 784) / 255.0
    y_train = train_ds.targets.long()
    x_test = test_ds.data.float().view(-1, 784) / 255.0
    y_test = test_ds.targets.long()

    if quick:
        # Smoke-test only; use the full dataset for the actual submission.
        x_train, y_train = x_train[:12000], y_train[:12000]
        x_test, y_test = x_test[:3000], y_test[:3000]
    return x_train, y_train, x_test, y_test


# ------------------------- Manual neural network ---------------------------

def activation_forward(z, name):
    if name == "relu":
        return z.clamp(min=0)
    if name == "sigmoid":
        # Clamp avoids overflow in exp for extreme values.
        return torch.sigmoid(z)
    if name == "tanh":
        return torch.tanh(z)
    if name == "leaky_relu":
        return torch.where(z > 0, z, 0.01 * z)
    raise ValueError(f"Unknown activation: {name}")


def activation_derivative(z, a, name):
    if name == "relu":
        return (z > 0).to(z.dtype)
    if name == "sigmoid":
        return a * (1.0 - a)
    if name == "tanh":
        return 1.0 - a.square()
    if name == "leaky_relu":
        return torch.where(z > 0, torch.ones_like(z), torch.full_like(z, 0.01))
    raise ValueError(f"Unknown activation: {name}")


class ManualMLP:
    """Fully connected MLP; parameters and gradients are managed manually."""

    def __init__(self, sizes, activation="relu", seed=42, device="cpu"):
        self.sizes = list(sizes)
        self.activation = activation
        self.device = torch.device(device)
        gen = torch.Generator(device="cpu")
        gen.manual_seed(seed)
        self.W, self.b = [], []
        for fan_in, fan_out in zip(self.sizes[:-1], self.sizes[1:]):
            if activation == "relu" or activation == "leaky_relu":
                scale = math.sqrt(2.0 / fan_in)  # He initialization
            else:
                scale = math.sqrt(1.0 / fan_in)  # Xavier-like initialization
            w = torch.randn(fan_in, fan_out, generator=gen) * scale
            bias = torch.zeros(fan_out)
            self.W.append(w.to(self.device))
            self.b.append(bias.to(self.device))
        self.zero_grad()

    def zero_grad(self):
        self.dW = [torch.zeros_like(w) for w in self.W]
        self.db = [torch.zeros_like(b) for b in self.b]

    def forward(self, x):
        # Match input dtype/device to parameters (also enables precise float64 gradient checks).
        x = x.to(device=self.device, dtype=self.W[0].dtype)
        activations = [x]
        preactivations = []
        h = x
        # Hidden layers use chosen activation; output layer returns logits.
        for i in range(len(self.W) - 1):
            z = h @ self.W[i] + self.b[i]
            preactivations.append(z)
            h = activation_forward(z, self.activation)
            activations.append(h)
        logits = h @ self.W[-1] + self.b[-1]
        preactivations.append(logits)
        activations.append(logits)
        return logits, activations, preactivations

    @staticmethod
    def loss_from_logits(logits, y):
        # Stable log-softmax + cross-entropy, averaged over mini-batch.
        log_probs = torch.log_softmax(logits, dim=1)
        return -log_probs[torch.arange(y.shape[0], device=y.device), y].mean()

    def backward(self, y, activations, preactivations):
        """Analytical gradients for mean softmax-cross-entropy."""
        batch_size = y.shape[0]
        logits = preactivations[-1]
        probs = torch.softmax(logits, dim=1)
        probs[torch.arange(batch_size, device=y.device), y] -= 1.0
        delta = probs / batch_size

        last = len(self.W) - 1
        self.dW[last] = activations[-2].T @ delta
        self.db[last] = delta.sum(dim=0)
        delta = delta @ self.W[last].T

        # Backpropagate from last hidden layer to first hidden layer.
        for i in range(last - 1, -1, -1):
            z = preactivations[i]
            a = activations[i + 1]
            delta = delta * activation_derivative(z, a, self.activation)
            self.dW[i] = activations[i].T @ delta
            self.db[i] = delta.sum(dim=0)
            if i > 0:
                delta = delta @ self.W[i].T

    def step(self, learning_rate):
        with torch.no_grad():
            for i in range(len(self.W)):
                self.W[i] -= learning_rate * self.dW[i]
                self.b[i] -= learning_rate * self.db[i]

    def predict(self, x, batch_size=1024):
        predictions = []
        with torch.no_grad():
            for start in range(0, len(x), batch_size):
                xb = x[start:start + batch_size].to(self.device)
                logits, _, _ = self.forward(xb)
                predictions.append(logits.argmax(dim=1).cpu())
        return torch.cat(predictions)

    def accuracy(self, x, y):
        return (self.predict(x) == y.cpu()).float().mean().item() * 100.0


# ------------------------------ Training -----------------------------------

def train_model(x_train, y_train, x_test, y_test, *,
                sizes=(784, 256, 128, 10), activation="relu",
                learning_rate=0.05, batch_size=128, epochs=10, seed=42,
                device="cpu", noisy_fraction=0.0, noise_std=0.3,
                augment_rotation=False, run_name="run"):
    """Train manually; optional noise affects a random fraction of training examples."""
    set_seed(seed)
    model = ManualMLP(sizes, activation, seed=seed, device=device)
    n = len(x_train)
    noisy_count = int(n * noisy_fraction)
    noisy_indices = torch.randperm(n)[:noisy_count] if noisy_count else None
    noisy_mask = torch.zeros(n, dtype=torch.bool)
    if noisy_indices is not None:
        noisy_mask[noisy_indices] = True

    history = {"loss": [], "test_accuracy": [], "train_accuracy": []}
    start_time = time.time()

    for epoch in range(1, epochs + 1):
        order = torch.randperm(n)
        total_loss, seen = 0.0, 0

        for start in range(0, n, batch_size):
            ids = order[start:start + batch_size]
            xb = x_train[ids].clone()
            yb = y_train[ids].to(device)

            # Mission 4: Gaussian noise, standard deviation 0.3, on 20% of
            # training images. Clip back to the valid pixel range [0, 1].
            if noisy_fraction > 0:
                selected = noisy_mask[ids]
                if selected.any():
                    noise = torch.randn_like(xb[selected]) * noise_std
                    xb[selected] = (xb[selected] + noise).clamp(0.0, 1.0)

            # Optional defence: random small rotations of training images.
            # Implemented with torchvision affine on a batch of image tensors.
            if augment_rotation:
                image_batch = xb.view(-1, 1, 28, 28)
                angle = (torch.rand(len(xb)) * 30.0 - 15.0).tolist()
                rotated = []
                for image, degrees in zip(image_batch, angle):
                    rotated.append(transforms.functional.rotate(
                        image, degrees, interpolation=transforms.InterpolationMode.BILINEAR
                    ))
                xb = torch.stack(rotated).view(-1, 784)

            xb = xb.to(device)
            logits, activations, preactivations = model.forward(xb)
            loss = model.loss_from_logits(logits, yb)
            model.zero_grad()
            model.backward(yb, activations, preactivations)
            model.step(learning_rate)

            total_loss += loss.item() * len(ids)
            seen += len(ids)

        mean_loss = total_loss / seen
        test_acc = model.accuracy(x_test, y_test)
        # Training accuracy uses a deterministic subset for speed.
        subset = min(5000, len(x_train))
        train_acc = model.accuracy(x_train[:subset], y_train[:subset])
        history["loss"].append(mean_loss)
        history["test_accuracy"].append(test_acc)
        history["train_accuracy"].append(train_acc)
        print(f"{run_name} | epoch {epoch:02d}/{epochs} | "
              f"loss={mean_loss:.4f} | train_acc={train_acc:.2f}% | "
              f"test_acc={test_acc:.2f}%")

    history["seconds"] = time.time() - start_time
    history["final_test_accuracy"] = history["test_accuracy"][-1]
    history["epochs_to_95"] = next(
        (i + 1 for i, a in enumerate(history["test_accuracy"]) if a >= 95.0), None
    )
    return model, history


# ----------------------- Mission 3: gradient check ------------------------

def gradient_check(model, x, y, epsilon=1e-5, checks_per_layer=1):
    """Compare analytic gradients with central finite differences in float64."""
    # Double precision is important because epsilon=1e-5 is too small for a
    # reliable central difference in float32.
    model.W = [w.detach().double() for w in model.W]
    model.b = [b.detach().double() for b in model.b]
    x = x[:min(8, len(x))].to(device=model.device, dtype=torch.float64)
    y = y[:len(x)].to(model.device)
    logits, activations, preactivations = model.forward(x)
    loss = model.loss_from_logits(logits, y)
    model.zero_grad()
    model.backward(y, activations, preactivations)

    print("\nGRADIENT CHECK (central finite difference)")
    print("relative_error = |analytic - numerical| / max(1e-12, |analytic| + |numerical|)")
    all_errors = []
    with torch.no_grad():
        for layer in range(len(model.W)):
            # Check one or more representative weights in each layer.
            indices = [(0, 0), (model.W[layer].shape[0] // 2,
                                model.W[layer].shape[1] // 2)][:checks_per_layer]
            for r, c in indices:
                analytic = model.dW[layer][r, c].item()
                original = model.W[layer][r, c].item()

                model.W[layer][r, c] = original + epsilon
                plus_logits, _, _ = model.forward(x)
                plus_loss = model.loss_from_logits(plus_logits, y).item()

                model.W[layer][r, c] = original - epsilon
                minus_logits, _, _ = model.forward(x)
                minus_loss = model.loss_from_logits(minus_logits, y).item()

                model.W[layer][r, c] = original
                numerical = (plus_loss - minus_loss) / (2.0 * epsilon)
                rel_error = abs(analytic - numerical) / max(
                    1e-12, abs(analytic) + abs(numerical)
                )
                all_errors.append(rel_error)
                print(f"layer {layer + 1}, W[{r},{c}]: "
                      f"analytic={analytic:.8e}, numerical={numerical:.8e}, "
                      f"relative_error={rel_error:.3e}")
    max_error = max(all_errors) if all_errors else float("inf")
    print(f"Maximum relative error: {max_error:.3e}")
    print("PASS (< 1e-5):", max_error < 1e-5)
    return max_error


def mean_first_hidden_gradient(model, x, y):
    x = x[:min(256, len(x))].to(model.device)
    y = y[:len(x)].to(model.device)
    logits, activations, preactivations = model.forward(x)
    model.zero_grad()
    model.backward(y, activations, preactivations)
    value = model.dW[0].abs().mean().item()
    print(f"Mean absolute gradient of first hidden layer weights: {value:.8e}")
    return value


# ------------------------------ Utilities ----------------------------------

def save_loss_plot(histories, output_dir, filename="mission3_loss.png"):
    plt.figure(figsize=(9, 5))
    for name, hist in histories.items():
        plt.plot(range(1, len(hist["loss"]) + 1), hist["loss"], label=name)
    plt.xlabel("Epoch")
    plt.ylabel("Training cross-entropy loss")
    plt.title("Mission 3: Activation Function Loss Comparison")
    plt.grid(True, alpha=0.3)
    plt.legend()
    plt.tight_layout()
    path = Path(output_dir) / filename
    plt.savefig(path, dpi=160)
    plt.close()
    print(f"Saved plot: {path}")


def save_experiment_log(rows, output_dir):
    path = Path(output_dir) / "mission2_experiment_log.csv"
    fields = ["run", "hidden_layers", "activation", "learning_rate",
              "batch_size", "epochs", "final_test_accuracy",
              "epochs_to_95", "seconds", "lesson"]
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Saved experiment log: {path}")


# -------------------------------- Main -------------------------------------

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true",
                        help="smoke-test using a smaller MNIST subset; not final results")
    parser.add_argument("--data-dir", default="./data")
    parser.add_argument("--output-dir", default="./ann_results")
    parser.add_argument("--epochs", type=int, default=10)
    parser.add_argument("--mission2-epochs", type=int, default=15)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    set_seed(args.seed)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"Device: {device}")
    print("Loading MNIST; pixels are scaled to [0, 1]...")
    x_train, y_train, x_test, y_test = load_mnist(args.data_dir, args.quick)
    print(f"Train: {len(x_train)} images; test: {len(x_test)} images")

    # Mission 1: transparent manual training pipeline.
    print("\n" + "=" * 18 + " MISSION 1 " + "=" * 18)
    base_epochs = 3 if args.quick else args.epochs
    base_model, base_hist = train_model(
        x_train, y_train, x_test, y_test,
        sizes=(784, 256, 128, 10), activation="relu",
        learning_rate=0.05, batch_size=128, epochs=base_epochs,
        seed=args.seed, device=device, run_name="Mission1"
    )
    print(f"Mission 1 final test accuracy: {base_hist['final_test_accuracy']:.2f}%")

    # Mission 2: six logged experiments. Same data split; one variable or
    # small set of variables changes between runs. Run the full dataset for submission.
    print("\n" + "=" * 18 + " MISSION 2 " + "=" * 18)
    exp_epochs = 2 if args.quick else args.mission2_epochs
    configs = [
        ("Run1_baseline", (784, 128, 10), "relu", 0.05, 128,
         "Baseline establishes a reference."),
        ("Run2_wider", (784, 256, 10), "relu", 0.05, 128,
         "More hidden units can model more complex patterns."),
        ("Run3_deeper", (784, 256, 128, 10), "relu", 0.05, 128,
         "A second hidden layer learns hierarchical features."),
        ("Run4_lower_lr", (784, 256, 128, 10), "relu", 0.01, 128,
         "A smaller learning rate may train more steadily but slower."),
        ("Run5_batch64", (784, 256, 128, 10), "relu", 0.05, 64,
         "Smaller batches update more often but have noisier gradients."),
        ("Run6_tanh", (784, 256, 128, 10), "tanh", 0.05, 128,
         "Tanh is zero-centred but can saturate and weaken gradients."),
    ]
    experiment_rows = []
    mission2_histories = {}
    for idx, (name, sizes, act, lr, bs, lesson) in enumerate(configs):
        _, hist = train_model(
            x_train, y_train, x_test, y_test,
            sizes=sizes, activation=act, learning_rate=lr,
            batch_size=bs, epochs=exp_epochs, seed=args.seed + idx,
            device=device, run_name=name
        )
        mission2_histories[name] = hist
        experiment_rows.append({
            "run": name,
            "hidden_layers": str(list(sizes[1:-1])),
            "activation": act,
            "learning_rate": lr,
            "batch_size": bs,
            "epochs": exp_epochs,
            "final_test_accuracy": f"{hist['final_test_accuracy']:.2f}",
            "epochs_to_95": hist["epochs_to_95"] if hist["epochs_to_95"] is not None else "not reached",
            "seconds": f"{hist['seconds']:.1f}",
            "lesson": lesson,
        })
    save_experiment_log(experiment_rows, out)
    best_name = max(mission2_histories,
                    key=lambda name: mission2_histories[name]["final_test_accuracy"])
    best_acc = mission2_histories[best_name]["final_test_accuracy"]
    print(f"\nBest measured Mission 2 run: {best_name} ({best_acc:.2f}%)")
    if best_acc >= 97:
        print("Target achieved: at least 97% test accuracy.")
    else:
        print("Target not reached yet. Try more epochs, tune learning rate/width, "
              "and rerun; report only measured results.")

    # Mission 3: identical architecture, LR, batch size and epoch count;
    # only activation changes. Separate model initializations use same seed.
    print("\n" + "=" * 18 + " MISSION 3 " + "=" * 18)
    m3_epochs = 2 if args.quick else args.mission2_epochs
    activation_histories, activation_models = {}, {}
    for act in ("relu", "sigmoid", "tanh"):
        model, hist = train_model(
            x_train, y_train, x_test, y_test,
            sizes=(784, 128, 64, 10), activation=act,
            learning_rate=0.05, batch_size=128, epochs=m3_epochs,
            seed=args.seed + 100, device=device, run_name=f"Mission3_{act}"
        )
        activation_histories[act] = hist
        activation_models[act] = model
    save_loss_plot(activation_histories, out)
    print("\nEpochs needed to reach 95% test accuracy:")
    for act, hist in activation_histories.items():
        print(f"  {act}: {hist['epochs_to_95'] if hist['epochs_to_95'] else 'not reached'}")

    # Gradient-check a small, fixed batch; finite differences are expensive
    # but this check is intentionally small.
    print("\nGradient verification on ReLU network:")
    check_model = activation_models["relu"]
    gradient_check(check_model, x_train[:8], y_train[:8], epsilon=1e-5)
    print("\nFirst hidden layer mean absolute gradient by activation:")
    grad_means = {}
    for act, model in activation_models.items():
        grad_means[act] = mean_first_hidden_gradient(model, x_train[:256], y_train[:256])
    print("Interpretation: very small first-layer gradients indicate weak gradient flow. "
          "Sigmoid often has weaker gradients because its derivative is at most 0.25 "
          "and approaches 0 in saturated regions.")

    # Mission 4: noisy training and rotated test images, then one robustness defence.
    print("\n" + "=" * 18 + " MISSION 4 " + "=" * 18)
    m4_epochs = 2 if args.quick else args.epochs
    clean_model, clean_hist = train_model(
        x_train, y_train, x_test, y_test,
        sizes=(784, 256, 128, 10), activation="relu",
        learning_rate=0.05, batch_size=128, epochs=m4_epochs,
        seed=args.seed + 200, device=device, run_name="Mission4_clean"
    )
    noisy_model, noisy_hist = train_model(
        x_train, y_train, x_test, y_test,
        sizes=(784, 256, 128, 10), activation="relu",
        learning_rate=0.05, batch_size=128, epochs=m4_epochs,
        seed=args.seed + 200, device=device, noisy_fraction=0.20,
        noise_std=0.3, run_name="Mission4_noisy_train"
    )

    # Rotate each clean test image by 15 degrees.
    rotated_images = []
    for image in x_test.view(-1, 1, 28, 28):
        rotated_images.append(transforms.functional.rotate(
            image, 15.0, interpolation=transforms.InterpolationMode.BILINEAR
        ))
    x_test_rotated = torch.stack(rotated_images).view(-1, 784)

    clean_on_clean = clean_model.accuracy(x_test, y_test)
    clean_on_rotated = clean_model.accuracy(x_test_rotated, y_test)
    noisy_on_clean = noisy_model.accuracy(x_test, y_test)
    noisy_on_rotated = noisy_model.accuracy(x_test_rotated, y_test)
    print("\nMission 4 measured accuracy:")
    print(f"Clean-trained model, clean test:   {clean_on_clean:.2f}%")
    print(f"Clean-trained model, rotated test: {clean_on_rotated:.2f}%")
    print(f"Noisy-trained model, clean test:   {noisy_on_clean:.2f}%")
    print(f"Noisy-trained model, rotated test: {noisy_on_rotated:.2f}%")
    print(f"Rotation accuracy drop for clean-trained model: "
          f"{clean_on_clean - clean_on_rotated:.2f} percentage points")
    print(f"Effect of noisy training on clean-test accuracy: "
          f"{noisy_on_clean - clean_on_clean:+.2f} percentage points")

    # One defence: train on noisy data and apply rotation augmentation.
    robust_model, robust_hist = train_model(
        x_train, y_train, x_test, y_test,
        sizes=(784, 256, 128, 10), activation="relu",
        learning_rate=0.05, batch_size=128, epochs=m4_epochs,
        seed=args.seed + 201, device=device, noisy_fraction=0.20,
        noise_std=0.3, augment_rotation=True, run_name="Mission4_defence"
    )
    robust_rotated = robust_model.accuracy(x_test_rotated, y_test)
    print(f"Defence model, clean test:   {robust_model.accuracy(x_test, y_test):.2f}%")
    print(f"Defence model, rotated test: {robust_rotated:.2f}%")

    # Machine-readable results for report.
    summary_path = out / "mission4_results.txt"
    with summary_path.open("w", encoding="utf-8") as f:
        f.write("Mission 4 measured results (percent accuracy)\n")
        f.write(f"clean-trained / clean test: {clean_on_clean:.2f}\n")
        f.write(f"clean-trained / rotated test: {clean_on_rotated:.2f}\n")
        f.write(f"noisy-trained / clean test: {noisy_on_clean:.2f}\n")
        f.write(f"noisy-trained / rotated test: {noisy_on_rotated:.2f}\n")
        f.write(f"defence / clean test: {robust_model.accuracy(x_test, y_test):.2f}\n")
        f.write(f"defence / rotated test: {robust_rotated:.2f}\n")
    print(f"Saved Mission 4 results: {summary_path}")
    print(f"\nAll output files are in: {out.resolve()}")


if __name__ == "__main__":
    main()
